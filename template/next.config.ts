import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  typescript: {
    /**
     * Типы проверяются ДО сборки: `node scripts/lab.mjs check` первым делом
     * гоняет `tsc --noEmit` и без зелёного результата дальше не идёт. Здесь
     * отключён ПОВТОР той же проверки внутри сборки.
     *
     * Дело не только в лишней минуте. Для этой проверки Next поднимает
     * отдельный процесс, а на Windows он падает с `spawn EPERM`, когда
     * запуск дочерних процессов ограничен песочницей агента или антивирусом.
     * Сама проверка типов при этом не теряется — она просто живёт в одном
     * месте вместо двух.
     *
     * Если собираете руками, минуя lab.mjs, — сначала прогоняйте
     * `npx tsc --noEmit`, иначе ошибка типов уедет в сборку незамеченной.
     */
    ignoreBuildErrors: true,
  },

  experimental: {
    /**
     * Та же беда, что и с проверкой типов выше, но на другом этапе.
     * «Collecting page data» Next выполняет в отдельных воркерах, и по
     * умолчанию это ДОЧЕРНИЕ ПРОЦЕССЫ (child_process.fork). Песочница агента
     * их запускать не даёт — сборка падает с `Error: spawn EPERM` уже после
     * того, как код и типы прошли.
     *
     * workerThreads переводит те же воркеры на потоки внутри процесса
     * (worker_threads) — форка нет, запрещать нечего. Проверено 22.09.2026:
     * с этой опцией сборка зелёная, Next помечает её как экспериментальную,
     * но предупреждений и отличий в выдаче нет.
     *
     * cpus: 1 — чтобы на слабой машине не плодить потоки под каждое ядро.
     */
    workerThreads: true,
    cpus: 1,
  },
};

export default nextConfig;
